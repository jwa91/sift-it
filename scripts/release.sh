#!/usr/bin/env bash
# Releases sift: builds it, signs and notarizes it, publishes the archive as a GitHub release, and writes
# Casks/sift.rb to jwa91/homebrew-tap. That's what GoReleaser does for the rest of the jwa91 family; sift does it here
# because GoReleaser's Rust builder always runs `rustup target add`, which this machine's toolchain policy reserves for
# mise (see CLAUDE.md, Exceptions). Same archive name, checksums file, cask and commit message as GoReleaser's.
#
#   scripts/release.sh X.Y.Z        a release (through `make release`, with secrets from .env.template)
#   scripts/release.sh --snapshot   build, sign when it can, archive, and render the cask into dist/; publish nothing
set -euo pipefail

OWNER=jwa91
REPO=sift
TAP=homebrew-tap
DESCRIPTION="Search your files by what's in them, on-device with EmbeddingGemma 2"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

snapshot=false
if [[ "${1:-}" == "--snapshot" ]]; then
  snapshot=true
  version="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)"
else
  version="${1:?usage: scripts/release.sh X.Y.Z | --snapshot}"
fi
tag="v$version"
archive="sift_${version}_darwin_arm64.tar.gz"
stage="dist/sift_darwin_arm64"

rm -rf dist
mkdir -p "$stage"

# Build, and check it is the version being released.
make build
built="$(target/release/sift --version | awk '{print $2}')"
if [[ "$built" != "$version" ]]; then
  echo "release: the build says $built, not $version (Cargo.toml)" >&2
  exit 1
fi

# Sign and notarize. A release must be; a snapshot is when it can be.
cp target/release/sift "$stage/sift"
if [[ -n "${MACOS_SIGN_IDENTITY:-}" ]]; then
  scripts/codesign.sh aarch64-apple-darwin "$stage/sift"
elif ! $snapshot; then
  echo "release: MACOS_SIGN_IDENTITY unset — a release must be signed and notarized (run it through make release)" >&2
  exit 1
else
  echo "snapshot: not signed (MACOS_SIGN_IDENTITY unset)"
fi

# The archive (the binary with its license and docs, as GoReleaser packs them) and its checksum.
cp LICENSE README.md CHANGELOG.md "$stage/"
tar -czf "dist/$archive" -C "$stage" sift LICENSE README.md CHANGELOG.md
(cd dist && shasum -a 256 "$archive" > checksums.txt)
sha256="$(cut -d' ' -f1 dist/checksums.txt)"

# The cask.
cat > dist/sift.rb <<EOF
# This file was generated by sift's scripts/release.sh. DO NOT EDIT.
cask "sift" do
  version "$version"
  sha256 "$sha256"

  url "https://github.com/$OWNER/$REPO/releases/download/v#{version}/sift_#{version}_darwin_arm64.tar.gz"
  name "sift"
  desc "$DESCRIPTION"
  homepage "https://github.com/$OWNER/$REPO"

  livecheck do
    skip "Auto-generated on release."
  end

  depends_on arch: :arm64
  depends_on macos: :sonoma

  binary "sift"

  uninstall launchctl: "local.sift.indexer"

  zap trash: [
    "~/Library/Application Support/Sift",
    "~/Library/LaunchAgents/local.sift.indexer.plist",
  ]

  caveats <<~EOS
    sift needs its model once (865 MB):
      sift model download
    Then choose folders, and index in the background from login on:
      sift folders add ~/Documents
      sift service install
  EOS
end
EOF

# The release notes: this version's section of the changelog.
awk -v version="$version" '
  $0 ~ "^## \\[" version "\\]" { inside = 1; next }
  /^## \[/ { inside = 0 }
  inside { print }
' CHANGELOG.md > dist/notes.md
if [[ ! -s dist/notes.md ]]; then
  echo "release: CHANGELOG.md has no section for [$version]" >&2
  $snapshot || exit 1
fi

if $snapshot; then
  echo "snapshot in dist/: $archive ($sha256), sift.rb"
  exit 0
fi

# The GitHub release, with the gh token (GITHUB_TOKEN, from make release).
gh release create "$tag" "dist/$archive" dist/checksums.txt \
  --repo "$OWNER/$REPO" --title "$tag" --notes-file dist/notes.md --verify-tag

# The cask, committed to the tap through the API with the tap-writer token: tokens act through the API, people push
# over SSH (tap ADR 0002).
: "${HOMEBREW_TAP_GITHUB_TOKEN:?HOMEBREW_TAP_GITHUB_TOKEN unset (it comes from .env.template)}"
existing="$(GH_TOKEN="$HOMEBREW_TAP_GITHUB_TOKEN" gh api "repos/$OWNER/$TAP/contents/Casks/sift.rb" --jq .sha 2>/dev/null || true)"
args=(-X PUT "repos/$OWNER/$TAP/contents/Casks/sift.rb"
  -f message="feat(sift): cask update to $tag"
  -f content="$(base64 < dist/sift.rb | tr -d '\n')"
  -f branch=main)
[[ -n "$existing" ]] && args+=(-f sha="$existing")
GH_TOKEN="$HOMEBREW_TAP_GITHUB_TOKEN" gh api "${args[@]}" --jq '.commit.html_url'

echo "released $tag: brew install $OWNER/tap/sift"
