#!/usr/bin/env bash
# Releases sift-it: builds it, signs and notarizes it, publishes the archive as a GitHub release, and writes
# Casks/sift-it.rb to jwa91/homebrew-tap. That's what GoReleaser does for the rest of the jwa91 family; sift-it does it here
# because GoReleaser's Rust builder always runs `rustup target add`, which this machine's toolchain policy reserves for
# mise (see CLAUDE.md, Exceptions). Same archive name, checksums file, cask and commit message as GoReleaser's.
#
#   scripts/release.sh X.Y.Z        a release (through `make release`)
#   scripts/release.sh --snapshot   build, archive, and render the cask into dist/, unsigned; publish nothing
#
# It needs no secrets of its own: signing and notarizing use this Mac's keychain (scripts/codesign.sh), and the GitHub
# release and the cask use your gh login.
set -euo pipefail

OWNER=jwa91
REPO=sift-it
TAP=homebrew-tap
DESCRIPTION="Local file search for the terminal and Raycast, written in Rust"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

snapshot=false
if [[ "${1:-}" == "--snapshot" ]]; then
  snapshot=true
  version="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)"
else
  version="${1:?usage: scripts/release.sh X.Y.Z | --snapshot}"
fi
tag="v$version"
archive="sift-it_${version}_darwin_arm64.tar.gz"
stage="dist/sift-it_darwin_arm64"

rm -rf dist
mkdir -p "$stage"

# Build, and check it is the version being released.
make build
built="$(target/release/sift-it --version | awk '{print $2}')"
if [[ "$built" != "$version" ]]; then
  echo "release: the build says $built, not $version (Cargo.toml)" >&2
  exit 1
fi

# Sign and notarize: a release always is; a snapshot (CI's, or a dry run) isn't. sift-it-transcribe, the speech helper,
# goes beside sift-it: transcribe.cpp brings its own ggml, so it can't share sift-it's binary.
cp target/release/sift-it target/release/sift-it-transcribe "$stage/"
if $snapshot; then
  echo "snapshot: not signed"
else
  scripts/codesign.sh "$stage/sift-it" "$stage/sift-it-transcribe"
fi

# The archive (the binaries with the license and docs, as GoReleaser packs them) and its checksum.
cp LICENSE README.md CHANGELOG.md "$stage/"
tar -czf "dist/$archive" -C "$stage" sift-it sift-it-transcribe LICENSE README.md CHANGELOG.md
(cd dist && shasum -a 256 "$archive" > checksums.txt)
sha256="$(cut -d' ' -f1 dist/checksums.txt)"

# The cask.
cat > dist/sift-it.rb <<EOF
# This file was generated by sift-it's scripts/release.sh. DO NOT EDIT.
cask "sift-it" do
  version "$version"
  sha256 "$sha256"

  url "https://github.com/$OWNER/$REPO/releases/download/v#{version}/sift-it_#{version}_darwin_arm64.tar.gz"
  name "sift-it"
  desc "$DESCRIPTION"
  homepage "https://github.com/$OWNER/$REPO"

  livecheck do
    skip "Auto-generated on release."
  end

  depends_on arch: :arm64
  depends_on macos: :sonoma

  binary "sift-it"
  binary "sift-it-transcribe"

  uninstall launchctl: ["local.sift-it.indexer", "local.sift-it.engine"]

  zap trash: [
    "~/Library/Application Support/Sift It",
    "~/Library/LaunchAgents/local.sift-it.indexer.plist",
    "~/Library/LaunchAgents/local.sift-it.engine.plist",
  ]

  caveats <<~EOS
    sift-it needs its models once (1.6 GB; 865 MB to search, 740 MB to write down speech):
      sift-it model download
    Then choose folders, and index and search in the background from login on:
      sift-it folders add ~/Documents
      sift-it service install
  EOS
end
EOF

# The release notes: this version's section of the changelog.
awk -v version="$version" '
  $0 ~ "^## \\[" version "\\]" { inside = 1; next }
  /^## \[/ { inside = 0 }
  inside { print }
' CHANGELOG.md > dist/notes.md
if [[ ! -s dist/notes.md ]]; then
  echo "release: CHANGELOG.md has no section for [$version]" >&2
  $snapshot || exit 1
fi

if $snapshot; then
  echo "snapshot in dist/: $archive ($sha256), sift-it.rb"
  exit 0
fi

# The GitHub release, with your gh login.
gh release create "$tag" "dist/$archive" dist/checksums.txt \
  --repo "$OWNER/$REPO" --title "$tag" --notes-file dist/notes.md --verify-tag

# The cask, committed to the tap through the API with your gh login (tokens act through the API; people push over
# SSH: tap ADR 0002).
existing="$(gh api "repos/$OWNER/$TAP/contents/Casks/sift-it.rb" --jq .sha 2>/dev/null || true)"
args=(-X PUT "repos/$OWNER/$TAP/contents/Casks/sift-it.rb"
  -f message="feat(sift-it): cask update to $tag"
  -f content="$(base64 < dist/sift-it.rb | tr -d '\n')"
  -f branch=main)
[[ -n "$existing" ]] && args+=(-f sha="$existing")
gh api "${args[@]}" --jq '.commit.html_url'

echo "released $tag: brew install $OWNER/tap/sift-it"
